"""
build_website.py
----------------
Exports the analysis results to dashboard/assets/data/data.js so the
multi-page dashboard website (dashboard/*.html) can display them.

The website itself (HTML / CSS / JavaScript) is static. It needs no web
server and no internet connection: open dashboard/index.html in a browser.
Every number shown on the website comes from this export, which is produced
by the same pipeline as the report and charts.

Run on its own (after main.py has created the cleaned data):
    python src/build_website.py
"""

import json
from datetime import date

import numpy as np
import pandas as pd

import config

SITE_DIR = config.PROJECT_ROOT / "dashboard"
DATA_JS = SITE_DIR / "assets" / "data" / "data.js"

LEARNER_COLUMNS = [
    "learner_id", "age_group", "course_module", "device_type", "time_spent_hours",
    "videos_watched", "videos_available", "lessons_completed", "lessons_available",
    "quiz_score", "completion_status", "activity_count", "last_active_days",
    "lesson_progress_pct", "video_completion_pct", "engagement_score", "engagement_category",
]


def _json_default(value):
    """Convert NumPy / pandas values to plain Python types for JSON."""
    if hasattr(value, "item"):
        return value.item()
    return str(value)


def _table(df: pd.DataFrame) -> list:
    """DataFrame -> list of dicts; the index becomes a 'name' field."""
    table = df.reset_index()
    table = table.rename(columns={table.columns[0]: "name"})
    table.columns = [str(c) for c in table.columns]
    return table.to_dict(orient="records")


def build_website_data(data: pd.DataFrame, results: dict, insight_dict: dict, raw_rows: int) -> dict:
    corr = results["correlation"]
    slope, intercept = np.polyfit(data["time_spent_hours"], data["quiz_score"], 1)
    cleaning_log = []
    if config.CLEANING_LOG_FILE.exists():
        cleaning_log = [line for line in config.CLEANING_LOG_FILE.read_text(encoding="utf-8").splitlines()[2:]
                        if line.strip()]
    dictionary = pd.read_csv(config.DATA_DICTIONARY_FILE).to_dict(orient="records") \
        if config.DATA_DICTIONARY_FILE.exists() else []

    learners = data[LEARNER_COLUMNS].copy()
    learners["engagement_category"] = learners["engagement_category"].astype(str)

    return {
        "meta": {
            "title": "DA-015 Online Learning Engagement Analysis",
            "generated": date.today().isoformat(),
            "raw_rows": int(raw_rows),
            "clean_rows": int(len(data)),
            "seed": config.RANDOM_SEED,
            "modules": config.MODULES,
            "devices": config.DEVICES,
            "age_groups": config.AGE_GROUPS,
            "statuses": config.COMPLETION_STATUSES,
            "engagement_labels": config.ENGAGEMENT_LABELS,
            "engagement_weights": config.ENGAGEMENT_WEIGHTS,
            "engagement_thresholds": {"medium": config.ENGAGEMENT_BINS[1], "high": config.ENGAGEMENT_BINS[2]},
            "normalise_clip": list(config.NORMALISE_CLIP),
            "inactive_threshold_days": config.INACTIVE_THRESHOLD_DAYS,
        },
        "kpis": results["kpis"],
        "module": _table(results["module"]),
        "device": _table(results["device"]),
        "age": _table(results["age"]),
        "status": _table(results["status"]),
        "engagement_module": _table(results["engagement_module"]),
        "engagement_outcomes": _table(results["engagement_outcomes"]),
        "correlation": {"labels": list(corr.columns), "matrix": corr.values.round(2).tolist()},
        "regression": {
            "slope": round(float(slope), 4),
            "intercept": round(float(intercept), 4),
            "r": round(float(data["time_spent_hours"].corr(data["quiz_score"])), 3),
        },
        "insights": insight_dict["insights"],
        "recommendations": insight_dict["recommendations"],
        "cleaning_log": cleaning_log,
        "dictionary": dictionary,
        "learners": learners.to_dict(orient="records"),
    }


def build_website(data: pd.DataFrame, results: dict, insight_dict: dict, raw_rows: int):
    payload = build_website_data(data, results, insight_dict, raw_rows)
    DATA_JS.parent.mkdir(parents=True, exist_ok=True)
    js = ("// AUTO-GENERATED by src/build_website.py - do not edit by hand.\n"
          "window.DASHBOARD_DATA = "
          + json.dumps(payload, default=_json_default, separators=(",", ":"))
          + ";\n")
    DATA_JS.write_text(js, encoding="utf-8")
    print(f"[website] Saved {DATA_JS.relative_to(config.PROJECT_ROOT)} "
          f"-> open dashboard/index.html in your browser")
    return DATA_JS


if __name__ == "__main__":
    from analysis import run_eda
    from engagement import add_engagement_score
    from generate_data import get_raw_dataset
    from insights import generate_insights

    if not config.CLEAN_DATA_FILE.exists():
        raise SystemExit("Cleaned data not found - run  python src/main.py  first.")
    df = add_engagement_score(pd.read_csv(config.CLEAN_DATA_FILE))
    res = run_eda(df, save=False)
    build_website(df, res, generate_insights(df, res), len(get_raw_dataset()))
