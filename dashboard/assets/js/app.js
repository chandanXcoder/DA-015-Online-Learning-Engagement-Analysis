  /* ---------------- global search ---------------- */
  function initSearch() {
    const input = DA.$("#globalSearch"), box = DA.$("#searchResults");
    let items = [], hl = 0;
    function render(q) {
      q = q.trim().toLowerCase();
      if (!q) { box.classList.remove("open"); return; }
      const pages = DA.routes.filter((r) => r.label.toLowerCase().includes(q)).map((r) => ({ grp: "Pages", icon: r.icon, label: r.label, href: r.href }));
      const mods = DA.data ? DA.data.meta.modules.filter((m) => m.toLowerCase().includes(q)).map((m) => ({ grp: "Modules", icon: "book-open", label: m, href: `modules.html#module=${encodeURIComponent(m)}` })) : [];
      const learners = DA.data ? DA.data.learners.filter((l) => l.learner_id.toLowerCase().includes(q)).slice(0, 6)
        .map((l) => ({ grp: "Learners", icon: "user", label: l.learner_id, meta: `${l.course_module} · ${l.completion_status}`, href: `learners.html#id=${l.learner_id}` })) : [];
      items = [...pages, ...mods, ...learners];
      hl = 0;
      let last = "";
      box.innerHTML = items.length ? items.map((it, i) => {
        const head = it.grp !== last ? `<div class="grp">${it.grp}</div>` : "";
        last = it.grp;
        return `${head}<a href="${it.href}" class="${i === 0 ? "hl" : ""}">${DA.icon(it.icon)}${DA.esc(it.label)}${it.meta ? `<small>${DA.esc(it.meta)}</small>` : ""}</a>`;
      }).join("") : `<div class="empty">${DA.icon("search-x")}No results for “${DA.esc(q)}”</div>`;
      box.classList.add("open");
      DA.paintIcons();
    }
    input.addEventListener("input", () => render(input.value));
    input.addEventListener("focus", () => input.value && render(input.value));
    input.addEventListener("keydown", (e) => {
      const links = DA.$$("a", box);
      if (!links.length) return;
      if (e.key === "ArrowDown" || e.key === "ArrowUp") {
        e.preventDefault();
        hl = (hl + (e.key === "ArrowDown" ? 1 : -1) + links.length) % links.length;
        links.forEach((a, i) => a.classList.toggle("hl", i === hl));
      } else if (e.key === "Enter") { e.preventDefault(); links[hl].click(); }
    });
    document.addEventListener("click", (e) => { if (!e.target.closest(".search")) box.classList.remove("open"); });
  }

  /* ---------------- page transitions ---------------- */
  function enableTransitions() {
    document.addEventListener("click", (e) => {
      const a = e.target.closest("a");
      if (!a || a.target === "_blank" || e.ctrlKey || e.metaKey || e.shiftKey || e.button !== 0) return;
      const href = a.getAttribute("href");
      if (!href || !/^[\w-]+\.html(#.*)?$/.test(href)) return;
      const samePage = href.split("#")[0] === (location.pathname.split("/").pop() || "index.html");
      if (samePage) { if (href.includes("#")) { setTimeout(() => window.dispatchEvent(new HashChangeEvent("hashchange")), 0); } return; }
      e.preventDefault();
      document.body.classList.add("leaving");
      setTimeout(() => (window.location.href = href), 180);
    });
    window.addEventListener("pageshow", (e) => {
      if (e.persisted) { document.body.classList.remove("leaving", "nav-open"); document.body.classList.add("ready"); }
    });
  }

