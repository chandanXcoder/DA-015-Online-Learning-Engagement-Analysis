  DA.md = (s) => DA.esc(s).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  DA.fmt = (n, d = 1) => (n == null || isNaN(n) ? "–" : Number(n).toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d }));
  DA.int = (n) => (n == null || isNaN(n) ? "–" : Math.round(n).toLocaleString("en-US"));
