  /* Percentile with linear interpolation (same method as pandas .quantile). */
  DA.quantile = function (values, q) {
    const s = values.slice().sort((a, b) => a - b);
    const pos = (s.length - 1) * q, lo = Math.floor(pos), hi = Math.ceil(pos);
    return s[lo] + (s[hi] - s[lo]) * (pos - lo);
  };
  let bounds = null;
  /** Contribution of each component to a learner's engagement score (mirrors src/engagement.py). */
  DA.engagementBreakdown = function (row) {
    const D = DA.data, [ql, qh] = D.meta.normalise_clip;
    if (!bounds) {
      bounds = {};
      Object.keys(D.meta.engagement_weights).forEach((k) => {
        const vals = D.learners.map((l) => l[k]);
        bounds[k] = [DA.quantile(vals, ql), DA.quantile(vals, qh)];
      });
    }
    return Object.entries(D.meta.engagement_weights).map(([k, w]) => {
      const [lo, hi] = bounds[k];
      const norm = hi === lo ? 0 : (Math.min(Math.max(row[k], lo), hi) - lo) / (hi - lo);
      return { key: k, weight: w, norm, points: norm * w * 100 };
    });
  };

