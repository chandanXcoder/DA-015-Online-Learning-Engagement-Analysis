  /** Summary statistics for any list of learner rows. */
  DA.summarise = (rows) => {
    const n = rows.length;
    const share = (fn) => (n ? (rows.filter(fn).length / n) * 100 : NaN);
    const inactiveDays = DA.data ? DA.data.meta.inactive_threshold_days : 30;
    return {
      learners: n,
      completed: rows.filter((r) => r.completion_status === "Completed").length,
      completion: share((r) => r.completion_status === "Completed"),
      dropout: share((r) => r.completion_status === "Dropped"),
      inProgress: share((r) => r.completion_status === "In Progress"),
      quiz: DA.mean(rows.map((r) => r.quiz_score)),
      hours: DA.mean(rows.map((r) => r.time_spent_hours)),
      totalHours: rows.reduce((a, r) => a + r.time_spent_hours, 0),
      engagement: DA.mean(rows.map((r) => r.engagement_score)),
      progress: DA.mean(rows.map((r) => r.lesson_progress_pct)),
      video: DA.mean(rows.map((r) => r.video_completion_pct)),
      activity: DA.mean(rows.map((r) => r.activity_count)),
      inactive: share((r) => r.last_active_days > inactiveDays),
      inactiveCount: rows.filter((r) => r.last_active_days > inactiveDays).length,
    };
  };

